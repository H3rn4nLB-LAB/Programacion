public class TablaDelNueve {

	public static void main(String[] args) {

		System.out.println("Tabla de multiplicar del 9");
		System.out.println("--------------------------");

		for (int i = 1; i <= 10; i++) {
			int resultado = 9 * i;

			System.out.println("9 x " + i + " = " + resultado);
		}

	}

}

